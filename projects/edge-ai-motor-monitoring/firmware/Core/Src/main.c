extern volatile uint8_t mt_inspection_action;
extern volatile uint8_t mt_fault_pending;

static const char *inspection_cgi(
    int index,
    int num_params,
    char *params[],
    char *values[])
{
    (void)index;

    if (!mt_fault_pending)
        return "/data";

    for (int i = 0; i < num_params; i++)
    {
        if (strcmp(params[i], "choice") != 0)
            continue;

        if (strcmp(values[i], "solved") == 0)
            mt_inspection_action = 1U;
        else if (strcmp(values[i], "accepted") == 0)
            mt_inspection_action = 2U;
        else if (strcmp(values[i], "notdone") == 0)
            mt_inspection_action = 3U;

        break;
    }

    return "/data";
}

static const tCGI inspection_cgi_table[] = {
    {"/inspect.cgi", inspection_cgi}
};
